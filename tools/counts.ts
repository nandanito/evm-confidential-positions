/**
 * counts.ts — the numbers the README quotes about this repository, derived, never typed.
 *
 * The reference project's recurring defect was hardcoded counts that went stale. Here every
 * count in README.md's generated block comes from this script, and `npm run check` fails if
 * the block no longer matches what the script derives.
 *
 * What it derives:
 *   - files: every file git would commit (tracked + untracked-but-not-ignored), by top dir;
 *   - the disclosure gate: files it scans, rules, CLAIMS rows those rules enforce, required
 *     disclosures, and the bad/good control samples (imported from the gate, not re-parsed);
 *   - tests: by running `npm test` and reading the runner's own TAP summary;
 *   - walkthrough checks: passed/total in each DATED archived run under example/out/
 *     (`*-latest.*` is excluded: every run rewrites it, so it cannot be quoted);
 *   - the register: CLAIMS.md rows by section, and the GAP rows (open vs closed).
 *
 * Usage:
 *   npm run counts          rewrite the block in README.md
 *   npm run check:counts    exit 1 if the block in README.md is stale (used by `npm run check`)
 */
import { spawnSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { REQUIRED, RULES, claimsRows, liveFiles } from "./check-disclosure.ts";

const ROOT = join(fileURLToPath(new URL(".", import.meta.url)), "..");
export const BEGIN = "<!-- counts:begin — generated by `npm run counts`; `npm run check` fails if stale. Do not edit by hand. -->";
export const END = "<!-- counts:end -->";

function fail(msg: string): never {
  console.error(`FAIL: ${msg}`);
  process.exit(1);
}

function repoFiles(): string[] {
  const r = spawnSync("git", ["ls-files", "--cached", "--others", "--exclude-standard"], { cwd: ROOT, encoding: "utf8" });
  if (r.status !== 0) fail(`git ls-files failed: ${r.stderr}`);
  // A tracked file deleted in the working tree is still listed by --cached; count what exists.
  return r.stdout.split("\n").filter((f) => f && existsSync(join(ROOT, f)));
}

/** Run the real test suite and read the runner's TAP summary (the reporter when piped). */
export function testSummary(): { tests: number; pass: number; fail: number } {
  const r = spawnSync("npm", ["test", "--silent"], { cwd: ROOT, encoding: "utf8", env: { ...process.env, NODE_TEST_CONTEXT: undefined } });
  const out = (r.stdout ?? "") + (r.stderr ?? "");
  const num = (k: string) => {
    const m = new RegExp(`^# ${k} (\\d+)$`, "m").exec(out);
    if (!m) fail(`could not read "# ${k}" from the test runner's output (exit ${r.status}):\n${out.slice(-2000)}`);
    return Number(m[1]);
  };
  const s = { tests: num("tests"), pass: num("pass"), fail: num("fail") };
  if (s.fail > 0 || r.status !== 0) fail(`the test suite fails (${s.fail} of ${s.tests}); fix it before counting it:\n${out.slice(-2000)}`);
  return s;
}

/** passed/total per dated archived run; a crashed or partly failing run is reported as such. */
function archivedRuns(): Array<{ file: string; passed: number; total: number; crashed: boolean }> {
  const dir = join(ROOT, "example", "out");
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => /^(run|auditor)-\d{4}-\d{2}-\d{2}[a-z]?\.json$/.test(f))
    .sort()
    .map((f) => {
      const j = JSON.parse(readFileSync(join(dir, f), "utf8")) as { checks?: Array<{ ok: boolean }>; crashed?: unknown };
      if (!Array.isArray(j.checks)) fail(`example/out/${f} has no checks[] array`);
      return { file: `example/out/${f}`, passed: j.checks.filter((c) => c.ok === true).length, total: j.checks.length, crashed: Boolean(j.crashed) };
    });
}

function gapRows(): { open: string[]; closed: string[] } {
  const text = readFileSync(join(ROOT, "docs", "task-zero", "GAPS-2026-09-26.md"), "utf8");
  const open: string[] = [];
  const closed: string[] = [];
  for (const m of text.matchAll(/^\|\s*(GAP-\d+)\s*\|([^|]*)\|/gm)) (/~~/.test(m[2]) ? closed : open).push(m[1]);
  if (open.length + closed.length === 0) fail("no GAP rows found in docs/task-zero/GAPS-2026-09-26.md");
  return { open, closed };
}

export function render(): string {
  const files = repoFiles();
  const byTop = new Map<string, number>();
  for (const f of files) {
    const top = f.includes("/") ? `${f.slice(0, f.indexOf("/"))}/` : "top level";
    byTop.set(top, (byTop.get(top) ?? 0) + 1);
  }
  const tops = [...byTop].sort(([a], [b]) => (a === "top level" ? -1 : b === "top level" ? 1 : a.localeCompare(b)));

  // Rules enforce prohibitions (P-) and contain findings held for private disclosure (F-). The
  // latter are counted, not named: their ids stay out of the README.
  const ruleRows = [...new Set(RULES.map((r) => r.id))];
  const ruleP = ruleRows.filter((id) => id.startsWith("P-"));
  const ruleOther = ruleRows.length - ruleP.length;
  const bad = RULES.reduce((n, r) => n + r.samples.bad.length, 0);
  const good = RULES.reduce((n, r) => n + r.samples.good.length, 0);

  const rows = claimsRows(readFileSync(join(ROOT, "CLAIMS.md"), "utf8"));
  const kinds = new Map<string, string[]>();
  for (const [id, k] of rows) kinds.set(k, [...(kinds.get(k) ?? []), id]);
  const ids = (k: string) => kinds.get(k) ?? [];
  const span = (list: string[]) => (list.length ? `${list[0]}..${list[list.length - 1]}` : "none");

  const t = testSummary();
  const runs = archivedRuns();
  const gaps = gapRows();

  const lines = [
    BEGIN,
    "",
    "| What | Count | Derived from |",
    "|---|---|---|",
    `| Files in the repository | ${files.length} (${tops.map(([d, n]) => `${d} ${n}`).join(", ")}) | \`git ls-files --cached --others --exclude-standard\` |`,
    `| Files the disclosure gate scans | ${liveFiles().length} | the gate's own scope list |`,
    `| Disclosure-gate rules | ${RULES.length}, enforcing ${ruleP.length} prohibitions (${span(ruleP)})${ruleOther ? ` and containing ${ruleOther} finding${ruleOther > 1 ? "s" : ""} held for private disclosure` : ""} | \`RULES\` in \`tools/check-disclosure.ts\` |`,
    `| Gate controls | ${bad} bad and ${good} good samples, run through the real detector on every scan | the same \`RULES\` |`,
    `| Required disclosures | ${REQUIRED.length} | \`REQUIRED\` in the same file |`,
    `| Tests | ${t.tests}, all passing | \`npm test\`, read from the runner's summary |`,
    ...runs.map((r) => `| Checks in \`${r.file}\` | ${r.passed}/${r.total} passed${r.crashed ? ", CRASHED" : ""} | its \`checks[]\` |`),
    `| CLAIMS rows | ${rows.size}: ${ids("prohibition").length} prohibitions (${span(ids("prohibition"))}), ${ids("established").length} established (${span(ids("established"))}), ${ids("pending").length} pending (${ids("pending").join(", ") || "none"}), ${ids("other").length} resolved (${ids("other").join(", ") || "none"}), ${ids("finding").length} findings (${span(ids("finding"))}), ${ids("retracted").length} retracted | \`CLAIMS.md\` |`,
    `| Gaps | ${gaps.open.length + gaps.closed.length}: ${gaps.open.length} open (${gaps.open.join(", ")}), ${gaps.closed.length} closed (${gaps.closed.join(", ") || "none"}) | \`docs/task-zero/GAPS-2026-09-26.md\` |`,
    "",
    END,
  ];
  return lines.join("\n");
}

export function spliceBlock(readme: string, block: string): string {
  const b = readme.indexOf(BEGIN);
  const e = readme.indexOf(END);
  if (b < 0 || e < 0 || e < b) fail(`README.md must contain exactly one counts block (${BEGIN} … ${END})`);
  if (readme.indexOf(BEGIN, b + 1) >= 0) fail("README.md contains more than one counts block");
  return readme.slice(0, b) + block + readme.slice(e + END.length);
}

function main(): void {
  const path = join(ROOT, "README.md");
  const readme = readFileSync(path, "utf8");
  spliceBlock(readme, ""); // validate the markers before the (slow) derivation
  const next = spliceBlock(readme, render());
  if (process.argv.includes("--check")) {
    if (next !== readme) {
      const cur = readme.slice(readme.indexOf(BEGIN), readme.indexOf(END) + END.length).split("\n");
      const want = next.slice(next.indexOf(BEGIN), next.indexOf(END) + END.length).split("\n");
      console.log("FAIL: the counts block in README.md is stale. Run `npm run counts`.");
      for (const l of cur) if (!want.includes(l)) console.log(`  - ${l}`);
      for (const l of want) if (!cur.includes(l)) console.log(`  + ${l}`);
      process.exit(1);
    }
    console.log("PASS: README.md counts block matches what tools/counts.ts derives.");
    return;
  }
  writeFileSync(path, next);
  console.log(next === readme ? "README.md counts block already current." : "README.md counts block rewritten.");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
